/** Backwards-compatible alias: the Georgia directory (the original single list). */
export const embassies = georgia

export function filterEmbassies(query, country = 'georgia') {
  const list = embassiesByCountry[country] || []
  if (!query || !query.trim()) return list
  const q = query.toLowerCase().trim()
  return list.filter(e =>
    e.countryName.toLowerCase().includes(q) ||
    e.embassyName.toLowerCase().includes(q) ||
    e.address.toLowerCase().includes(q)
  )
}
